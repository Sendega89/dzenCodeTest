export type Messages = typeof ru

export function messagesFor(locale: Locale): Messages {
  return locale === 'en' ? en : ru
}

export function productWord(count: number, locale: Locale): string {
  if (locale === 'en') return count === 1 ? 'product' : 'products'
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return 'продукт'
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'продукта'
  return 'продуктов'
}

export function textOf(messages: Messages, key: string): string {
  return messages.validation[key] ?? key
}
